  app.galaxy = createGalaxy(app);
  app.galaxyPanel = createGalaxyPanel(app);
  app.microscope = createMicroscope(app);
  app.importPreview = createImportPreview(app);
  app.permissions = createPermissions(app);
  app.boot = createBoot(app);
  app.overview = createOverview(app);
  app.search = createSearch(app);
  app.coreMemory = createCoreMemory(app);
  app.botLife = createBotLife(app);
  app.links = createLinks(app);
  app.capabilities = createCapabilities(app);
  app.knowledge = createKnowledge(app);
  app.importer = createImporter(app);
  app.maintenance = createMaintenance(app);
  app.settings = createSettings(app);
  await app.common.initialize();
  await app.api.initialize();
  await app.diagnostics.initialize();
  await app.shell.initialize();
  await app.appearance.initialize();
  await app.navigation.initialize();
  await app.records.initialize();
